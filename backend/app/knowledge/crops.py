def stage_kc(crop: dict, stage: str) -> float:
    """Map FAO-56 Kc (ini, mid, end) onto the spec's four growth stages (external)."""
    ini, mid, end = crop["kc_ext"]
    return {
        "establishment": ini,
        "vegetative": round((ini + mid) / 2, 2),
        "flowering": mid,
        "ripening": end,
    }[stage]


def stage_modifier(crop: dict, stage: str, nutrient: str) -> float:
    mods = crop.get("stage_mod_ext", {})
    value = mods.get("all", {}).get(nutrient, 1.0)
    value *= mods.get(stage, {}).get(nutrient, 1.0)
    return value
