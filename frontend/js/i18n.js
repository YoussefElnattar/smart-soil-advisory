let lang = (() => { try { return localStorage.getItem("soil.lang") || "en"; } catch { return "en"; } })();

export function getLang() { return lang; }
export function t(key) { const v = DICT[key]; return v ? v[lang === "ar" ? 1 : 0] : key; }
/** Pick the language-specific field from an object: L(obj, "message") → obj.message_en / obj.message_ar */
export function L(obj, base) {
  if (!obj) return "";
  return obj[`${base}_${lang}`] ?? obj[`${base}_en`] ?? obj[base] ?? "";
}
export function setLang(next) {
  lang = next;
  try { localStorage.setItem("soil.lang", lang); } catch { /* private mode */ }
  applyStatic();
}
export function applyStatic() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  const btn = document.getElementById("langBtn");
  if (btn) btn.textContent = lang === "ar" ? "English" : "العربية";
}
